#!/bin/sh
# Writes the Homebrew formula for a published release into the tap cj-ways/homebrew-acctswap,
# from the release's SHA256SUMS. Run it after each release, with a gh login that can write the tap.
#   scripts/update-tap.sh 0.2.0           write the formula
#   scripts/update-tap.sh 0.2.0 --print   only print it
set -eu
v=${1:?usage: scripts/update-tap.sh <version> [--print]}
repo=cj-ways/acctswap
tap=cj-ways/homebrew-acctswap
base=https://github.com/$repo/releases/download/v$v
sums=$(gh release download "v$v" -R "$repo" -p SHA256SUMS -O -)

sha() {
  s=$(printf '%s\n' "$sums" | awk -v f="acctswap-$1.tar.gz" '$2 == f { print $1 }')
  [ -n "$s" ] || { echo "no checksum for acctswap-$1.tar.gz in v$v" >&2; exit 1; }
  printf '%s' "$s"
}

formula=$(cat <<EOF
# Generated by scripts/update-tap.sh in $repo; edits here are overwritten.
class Acctswap < Formula
  desc "Switch the account every Claude Code session on a machine uses"
  homepage "https://github.com/$repo"
  version "$v"
  license any_of: ["MIT", "Apache-2.0"]

  on_macos do
    on_arm do
      url "$base/acctswap-aarch64-apple-darwin.tar.gz"
      sha256 "$(sha aarch64-apple-darwin)"
    end
    on_intel do
      url "$base/acctswap-x86_64-apple-darwin.tar.gz"
      sha256 "$(sha x86_64-apple-darwin)"
    end
  end

  on_linux do
    on_arm do
      url "$base/acctswap-aarch64-unknown-linux-musl.tar.gz"
      sha256 "$(sha aarch64-unknown-linux-musl)"
    end
    on_intel do
      url "$base/acctswap-x86_64-unknown-linux-musl.tar.gz"
      sha256 "$(sha x86_64-unknown-linux-musl)"
    end
  end

  def install
    bin.install "acctswap"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/acctswap --version")
  end
end
EOF
)

if [ "${2:-}" = "--print" ]; then
  printf '%s\n' "$formula"
  exit 0
fi
old=$(gh api "repos/$tap/contents/Formula/acctswap.rb" --jq .sha 2>/dev/null) || old= # none yet
gh api -X PUT "repos/$tap/contents/Formula/acctswap.rb" --silent \
  -f message="feat: acctswap $v" \
  -f content="$(printf '%s\n' "$formula" | base64 | tr -d '\n')" \
  ${old:+-f sha="$old"}
echo "tap updated: brew install cj-ways/acctswap/acctswap  (or: brew upgrade acctswap)"
